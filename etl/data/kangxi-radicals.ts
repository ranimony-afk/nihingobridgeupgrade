export const KANGXI_RADICALS: KangxiRadical[] = ROWS.map(
  ([number, character, variants, strokeCount, name]) => ({
    number,
    character,
    variants: Array.from(variants),
    strokeCount,
    name,
  }),
);

export const KANGXI_RADICAL_BY_NUMBER: Map<number, KangxiRadical> = new Map(
  KANGXI_RADICALS.map((radical) => [radical.number, radical]),
);

/** Glyph (canonical or variant) -> Kangxi radical number. */
export const RADICAL_CHARACTER_TO_NUMBER: Map<string, number> = (() => {
  const map = new Map<string, number>();
  for (const radical of KANGXI_RADICALS) {
    // Canonical glyph wins over variants so 月 stays #74 (moon) and 阝 #163.
    if (!map.has(radical.character)) map.set(radical.character, radical.number);
    for (const variant of radical.variants) {
      if (!map.has(variant)) map.set(variant, radical.number);
    }
  }
  return map;
})();

export function getKangxiRadical(number: number): KangxiRadical | undefined {
  return KANGXI_RADICAL_BY_NUMBER.get(number);
}

export function getKangxiRadicalByCharacter(character: string): KangxiRadical | undefined {
  const number = RADICAL_CHARACTER_TO_NUMBER.get(character);
  return number ? KANGXI_RADICAL_BY_NUMBER.get(number) : undefined;
}
